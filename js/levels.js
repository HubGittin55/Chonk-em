/* ================= food tiers & the 100-level chonk curve =================
   Owner's design (2026-10-06): new exotic food every 5 levels (+5 cal), per-level
   reset stays, and each level's TOTAL food scales so 80 lb is impossible on L10
   but reachable with near-perfect play on L50+. rawTarget(L) = 55 + 4*(L-1):
   L1→55 raw (21.5 lb max), L10→91 (32 lb), L50→251 (80 lb), L100→451 (140 lb). */

const NUM_LEVELS = 100;

const EXOTICS = [ // [key, name] — tier t (levels 10+5*(t-2)) unlocks cal 15+5*(t-2)
  ['caviar', 'Caviar'], ['lobster', 'Lobster'], ['wagyu', 'Wagyu'],
  ['btruffle', 'Black Truffle'], ['saffron', 'Saffron'], ['bluefin', 'Bluefin'],
  ['foiegras', 'Foie Gras'], ['goldkib', 'Gold Kibble'], ['kingcrab', 'King Crab'],
  ['uni', 'Uni'], ['kobe', 'Kobe'], ['matsutake', 'Matsutake'],
  ['beluga', 'Beluga'], ['iberico', 'Ibérico'], ['amberjack', 'Amberjack'],
  ['wtruffle', 'White Truffle'], ['saffris', 'Saffron Risotto'], ['imperial', 'Imperial Feast'],
];
function tierForLevel(n) { return Math.min(19, Math.floor(n / 5)); } // 1-based n → 0..19
function tierMaxCal(n) { return 5 + 5 * tierForLevel(n); }
function tierExotic(n) { const t = tierForLevel(n); return t >= 2 ? EXOTICS[t - 2][0] : null; }
function tierExoticName(n) { const t = tierForLevel(n); return t >= 2 ? EXOTICS[t - 2][1] : null; }
function rawTarget(n) { return Math.round(55 + 4 * (n - 1)); }
function tierCommons(n) { // snack keys legal on level n, ascending cal (CONTENT lives in barrels.js)
  const t = tierForLevel(n);
  const keys = ['kibble', 'salmon', 'tuna'];
  if (t >= 1) keys.push('turkey', 'shrimp', 'steak');
  for (let i = 2; i <= t; i++) keys.push(EXOTICS[i - 2][0]);
  return keys.filter(k => (CONTENT[k] || { cal: 999 }).cal <= tierMaxCal(n))
             .sort((a, b) => CONTENT[a].cal - CONTENT[b].cal);
}

function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const ARCHETYPES = ['full', 'diamond', 'ring', 'columns', 'checker', 'twin', 'wave'];
const GEN_NAMES_A = ['Grand', 'Mega', 'Hyper', 'Secret', 'Neon', 'Turbo', 'Royal', 'Cosmic'];
const GEN_NAMES_B = ['Feast', 'Pounce', 'Banquet', 'Gorge', 'Snackening', 'Munch', 'Chomp', 'Larder'];

function genLevel(n) { // 1-based, n >= 13. Deterministic — same n, same level, every load.
  const rnd = mulberry32(n * 7919 + 13);
  const R = 10, DX = 21, DY = 18.2;
  const pts = [];
  let row = 0;
  for (let y = 250; y <= 660; y += DY, row++)
    for (let x = 90 + (row % 2) * DX / 2; x <= 510; x += DX)
      pts.push({ x: Math.round(x), y: Math.round(y) });
  const arch = ARCHETYPES[Math.floor(rnd() * ARCHETYPES.length)];
  const keep = pts.filter(p => {
    const nx = (p.x - 300) / 220, ny = (p.y - 455) / 210;
    switch (arch) {
      case 'diamond': return Math.abs(nx) + Math.abs(ny) < 0.95;
      case 'ring': { const d = Math.hypot(nx, ny); return d > 0.45 && d < 1.0; }
      case 'columns': return [150, 250, 350, 450].some(c => Math.abs(p.x - c) < 24);
      case 'checker': { const ix = Math.round((p.x - 90) / DX), iy = Math.round((p.y - 250) / DY); return (ix + iy) % 2 === 0; }
      case 'twin': return Math.hypot(p.x - 200, p.y - 430) < 130 || Math.hypot(p.x - 400, p.y - 430) < 130;
      case 'wave': return Math.abs(p.y - (455 + 90 * Math.sin(p.x / 70))) < 120;
      default: return true;
    }
  });
  const set = new Set(keep.map(p => p.x + ',' + p.y));
  let final = keep.filter(p => set.has((600 - p.x) + ',' + p.y)); // hard left-right symmetry
  if (final.length < 60) final = pts.slice();
  // trim to ≤115 barrels, removing symmetric pairs
  let guard = 0;
  while (final.length > 115 && guard++ < 500) {
    const i = Math.floor(rnd() * final.length);
    const p = final[i], mx = 600 - p.x;
    final = final.filter(q => !(q.x === p.x && q.y === p.y) && !(q.x === mx && q.y === p.y));
  }

  const tier = tierForLevel(n), maxCal = tierMaxCal(n), exotic = tierExotic(n);
  const commons = tierCommons(n);
  const target = rawTarget(n);
  const order = final.slice();
  for (let i = order.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [order[i], order[j]] = [order[j], order[i]]; }
  const nB = order.length;
  const nEmpty = Math.round(nB * 0.5), nVeg = Math.round(nB * 0.12);
  const powers = ['split', 'multi', 'wide', 'slow', 'magnet'];
  const barrels = order.map((p, i) => {
    const b = { x: p.x, y: p.y, kind: 'empty', content: null };
    if (i < nEmpty) return b;
    if (i < nEmpty + nVeg) { b.kind = 'veggie'; b.content = i % 2 ? 'broccoli' : 'celery'; return b; }
    if (i < nEmpty + nVeg + 3) { b.kind = 'power'; b.content = powers[i - nEmpty - nVeg]; return b; }
    b.kind = 'snack';
    b.content = commons[Math.floor(rnd() * Math.min(3, commons.length))]; // mostly cheap
    if (rnd() < 0.15) b.armor = true;
    return b;
  });
  // seed 1-3 exotics (the jackpot barrels)
  const snacks = barrels.filter(b => b.kind === 'snack');
  if (exotic) {
    const nEx = 1 + Math.floor(rnd() * 3);
    for (let k = 0; k < nEx && k < snacks.length; k++) {
      const s = snacks[Math.floor(rnd() * snacks.length)];
      s.content = exotic; delete s.armor;
    }
  }
  // tune total raw cal to the curve
  const calOf = b => (CONTENT[b.content] || { cal: 0 }).cal;
  let raw = snacks.reduce((a, b) => a + calOf(b), 0);
  guard = 0;
  while (raw < target - 3 && guard++ < 600) {
    const cands = snacks.filter(b => b.content !== exotic && commons.indexOf(b.content) < commons.length - 1);
    if (!cands.length) break;
    const b = cands[Math.floor(rnd() * cands.length)];
    b.content = commons[commons.indexOf(b.content) + 1];
    raw = snacks.reduce((a, x) => a + calOf(x), 0);
  }
  guard = 0;
  while (raw > target + 3 && guard++ < 900) {
    const cands = snacks.filter(b => b.content !== exotic && calOf(b) > 1);
    if (!cands.length) break;
    const b = cands[Math.floor(rnd() * cands.length)];
    const ci = commons.indexOf(b.content);
    if (ci <= 0) { b.kind = 'empty'; b.content = null; snacks.splice(snacks.indexOf(b), 1); }
    else b.content = commons[ci - 1];
    raw = snacks.reduce((a, x) => a + calOf(x), 0);
  }
  // obstacles & toys: convert some empties — steel (unbreakable), keg (explodes), bumper (power bounce)
  const empt = barrels.filter(b => b.kind === 'empty');
  for (let i = empt.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [empt[i], empt[j]] = [empt[j], empt[i]]; }
  const nSteel = Math.max(2, Math.round(nB * 0.06));
  const nKeg = Math.max(1, Math.round(nB * 0.04));
  const nBump = Math.max(1, Math.round(nB * 0.04));
  empt.forEach((b, i) => {
    if (i < nSteel) { b.kind = 'steel'; }
    else if (i < nSteel + nKeg) { b.kind = 'keg'; }
    else if (i < nSteel + nKeg + nBump) { b.kind = 'bumper'; }
  });
  // every level keeps: split powerup, ≥1 armored snack
  if (!barrels.some(b => b.kind === 'power' && b.content === 'split')) {
    const pw = barrels.find(b => b.kind === 'power'); if (pw) pw.content = 'split';
  }
  if (!barrels.some(b => b.armor)) { const s = snacks[0]; if (s) s.armor = true; }

  const balls = Math.round(nB * 0.6);
  return {
    name: GEN_NAMES_A[Math.floor(rnd() * GEN_NAMES_A.length)] + ' ' +
          GEN_NAMES_B[Math.floor(rnd() * GEN_NAMES_B.length)],
    balls, par: Math.round(balls * 0.75), goal: Math.round(raw * 0.6), r: R,
    vacuum: n % 3 === 0,
    barrels,
  };
}

const _genCache = {};
function getLevel(i) { // 0-based index → level def; 0..11 handcrafted, 12+ procedural
  if (i < LEVELS.length) return LEVELS[i];
  const n = i + 1;
  if (!_genCache[n]) _genCache[n] = genLevel(n);
  return _genCache[n];
}
